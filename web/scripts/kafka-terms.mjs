/** Troca analogia da trilha pelos nomes do Kafka. */
export function kafkaTerms(s) {
  let t = String(s);
  t = t.replace(/linha do INSERT/gi, "«sql-row»");
  t = t.replace(/No caderno desta aula:\s*/gi, "");
  t = t.replace(/Na mesa,?\s*/gi, "");
  t = t.replace(/Analogia:\s*/gi, "");
  t = t.replace(/Na analogia da ata,?\s*/gi, "");
  t = t.replace(/Na analogia da família Silva,?\s*/gi, "");
  t = t.replace(/Na analogia,?\s*/gi, "");
  t = t.replace(/como numa fila do banco/gi, "como numa fila clássica (SQS)");
  t = t.replace(/fila do banco/gi, "fila clássica");
  t = t.replace(/crachás/gi, "group.id");
  t = t.replace(/crachá/gi, "group.id");
  t = t.replace(/cadernos/gi, "segmentos");
  t = t.replace(/caderno/gi, "log");
  t = t.replace(/páginas/gi, "tópicos");
  t = t.replace(/página/gi, "tópico");
  t = t.replace(/colunas/gi, "partições");
  t = t.replace(/coluna/gi, "partição");
  t = t.replace(/recados/gi, "mensagens");
  t = t.replace(/recado/gi, "mensagem");
  t = t.replace(/filmes independentes/gi, "consumos independentes");
  t = t.replace(/família Silva/gi, "mesma key");
  t = t.replace(/rasga a tópico/gi, "apaga a mensagem");
  t = t.replace(/própria marca “já li até aqui”/g, "próprio committed offset");
  t = t.replace(/marca “já li até aqui”/g, "committed offset");
  t = t.replace(/duas marcas/gi, "dois committed offsets");
  t = t.replace(/as marcas/gi, "os committed offsets");
  t = t.replace(/a marca do grupo/gi, "o committed offset do grupo");
  t = t.replace(/a própria marca/gi, "o próprio committed offset");
  t = t.replace(/sua marca/gi, "seu committed offset");
  t = t.replace(/a mesma marca/gi, "o mesmo committed offset");
  t = t.replace(/uma marca só/gi, "um committed offset só");
  t = t.replace(/uma marca/gi, "um committed offset");
  t = t.replace(/a marca/gi, "o committed offset");
  t = t.replace(/marcas independentes/gi, "committed offsets independentes");
  t = t.replace(/marcas/gi, "committed offsets");
  t = t.replace(/linhas/gi, "mensagens");
  t = t.replace(/\blinha\b/gi, "mensagem");
  t = t.replace(/«sql-row»/g, "linha do INSERT");
  t = t.replace(/canetada/gi, "gravação");
  t = t.replace(/\bcaneta\b/gi, "producer");
  t = t.replace(/caixinha/gi, "tabela outbox");
  t = t.replace(/\bcarteiro\b/gi, "poller");
  t = t.replace(/cartórios/gi, "Schema Registry");
  t = t.replace(/cartório/gi, "Schema Registry");
  return t.replace(/\s+/g, " ").trim();
}
